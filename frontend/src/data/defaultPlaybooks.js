export function computePlaybooks(astronautWeight = 75) {
  const calcDose = (drug, weight) => {
    if (!drug) return null;
    const dosePerKg = drug.dose_per_kg;
    let calculatedDose = drug.standard_dose;
    if (dosePerKg) {
      const raw = Math.round(dosePerKg * weight * 10) / 10;
      const formatted = Number.isInteger(raw) ? raw : raw.toFixed(1);
      const unit = drug.name.includes('ORS') || drug.name.includes('Fluid') ? 'mL' : 'mg';
      calculatedDose = `${formatted} ${unit} (Calculated at ${dosePerKg} ${unit}/kg for ${weight} kg)`;
    }
    return {
      ...drug,
      calculated_dose: calculatedDose,
    };
  };

  return Object.values(RAW_CATALOG).map((protocol) => ({
    ...protocol,
    primary_drug: calcDose(protocol.primary_drug, astronautWeight),
    secondary_drug: protocol.secondary_drug ? calcDose(protocol.secondary_drug, astronautWeight) : null,
  }));
}
